#!/usr/bin/env python3
"""Compress the dashboard page for the firmware.

src/page.h keeps the dashboard as plain, editable HTML (a C++ raw string). Storing it like that costs
~22 KB of the app partition; gzipped it is ~8 KB, and every browser unpacks it on its own
(main.cpp sends it with "Content-Encoding: gzip").

Two ways to run it:
  * PlatformIO: referenced from platformio.ini (extra_scripts = pre:tools/gzip_page.py). It writes
    <build dir>/gen/page_gz.h and adds that folder to the include path, so nothing is committed
    and the header is regenerated whenever page.h changes.
  * By hand:    python3 tools/gzip_page.py src/page.h /some/dir/page_gz.h
"""
import gzip
import io
import os
import re
import sys


def make_header(page_h):
    """Return (header_text, html_bytes, gzip_bytes) for the R"HTML(...)HTML" literal in page_h."""
    with open(page_h, encoding="utf-8") as f:
        m = re.search(r'R"HTML\((.*)\)HTML"', f.read(), re.S)
    if not m:
        raise SystemExit('gzip_page.py: no R"HTML(...)HTML" literal found in ' + page_h)
    raw = m.group(1).encode("utf-8")
    out = io.BytesIO()
    with gzip.GzipFile(fileobj=out, mode="wb", compresslevel=9, mtime=0) as g:   # mtime=0: reproducible output
        g.write(raw)
    gz = out.getvalue()
    rows = ",\n".join("  " + ",".join("0x%02x" % b for b in gz[i:i + 16]) for i in range(0, len(gz), 16))
    text = ("// generated by tools/gzip_page.py from src/page.h -- do not edit\n"
            "static const size_t PAGE_GZ_LEN = %d;\n"
            "static const uint8_t PAGE_GZ[] PROGMEM = {\n%s\n};\n") % (len(gz), rows)
    return text, len(raw), len(gz)


def write_if_changed(path, text):
    try:
        with open(path, encoding="utf-8") as f:
            if f.read() == text:
                return                                   # untouched -> no needless rebuild of main.cpp
    except OSError:
        pass
    with open(path, "w", encoding="utf-8") as f:
        f.write(text)


try:
    Import("env")                                        # noqa: F821  (only defined when SCons/PlatformIO runs this file)
except NameError:
    env = None

if env is not None:
    gen = os.path.join(env.subst("$BUILD_DIR"), "gen")
    os.makedirs(gen, exist_ok=True)
    text, n_raw, n_gz = make_header(os.path.join(env.subst("$PROJECT_DIR"), "src", "page.h"))
    write_if_changed(os.path.join(gen, "page_gz.h"), text)
    env.Append(CPPPATH=[gen])
    print("gzip_page: dashboard %d -> %d bytes" % (n_raw, n_gz))
elif __name__ == "__main__":
    if len(sys.argv) != 3:
        raise SystemExit("usage: gzip_page.py src/page.h out/page_gz.h")
    text, n_raw, n_gz = make_header(sys.argv[1])
    write_if_changed(sys.argv[2], text)
    print("gzip_page: dashboard %d -> %d bytes" % (n_raw, n_gz))
